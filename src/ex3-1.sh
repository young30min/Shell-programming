#!/bin/bash
# 숫자 2개를 인자로 받아서 사칙연산

# 인자가 2개가 아니면 사용법 출력
if [ $# -ne 2 ]; then
    echo "사용법: $0 숫자1 숫자2"
    exit 1
fi

echo "입력한 인자 개수: $#, 인자: $1, $2"
echo "덧셈: $1 + $2 = $(($1 + $2))"
echo "뺄셈: $1 - $2 = $(($1 - $2))"
echo "곱셈: $1 * $2 = $(($1 * $2))"

# 0으로 나누면 에러가 나서 따로 처리
if [ $2 -eq 0 ]; then
    echo "나눗셈: 0으로 나눌 수 없습니다."
else
    echo "나눗셈: $1 / $2 = $(($1 / $2))"
fi
